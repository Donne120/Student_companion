#!/usr/bin/env node
/**
 * Writes src/styles/dark-theme.css: the dark colours for every fixed light
 * colour the components use (text-[#1A1A1A], bg-white, border-[#E8DDB0]...).
 *
 * The chat was designed light-only with fixed colours in the markup, so the
 * Dark theme maps each of them to a dark-mode colour under `.dark` (set by
 * next-themes) instead of editing hundreds of components. Run it again after
 * adding new fixed colours:   node scripts/gen-dark-theme.mjs
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

// light colour -> dark colour, per kind of class. Missing = left as it is
// (gold, green and other accents read well on dark too).
const TEXT = {
  "#1A1A1A": "#ECE9E2", "#1C1B19": "#ECE9E2", "#262521": "#ECE9E2", "gray-700": "#D6D2C9", "black": "#ECE9E2",
  "#3C372E": "#D6D2C9", "#4A4437": "#D6D2C9", "#4A4843": "#D6D2C9", "#5C5647": "#C9C4B9",
  "#6B6355": "#B3AEA3", "#6B6862": "#B3AEA3", "#6B6559": "#B3AEA3",
  "#8C887F": "#9A968D", "#9C978C": "#9A968D", "#B5B0A5": "#8A867E",
  "#B8941F": "#E3C25E", "#8A6A16": "#E3C25E", "#8A6D12": "#E3C25E", "#B8860B": "#E3C25E",
  "#B83B3B": "#F28B82", "#9A3412": "#F4A574", "#2E7D32": "#7CCB82",
};
const BG = {
  "white": "#1E1D1B", "#FFFFFF": "#1E1D1B", "#FFFDF6": "#1E1D1B", "#FAFAF8": "#1E1D1B", "#FBFAF6": "#1E1D1B",
  "#FBF7E9": "#2B2719", "#FAF6E8": "#2B2719",
  "#F4F3F0": "#262522", "#F1F0EC": "#262522", "gray-50": "#262522", "gray-100": "#262522",
  "#E5E3DE": "#34322D", "#EDEBE6": "#34322D", "#9C978C": "#55524B",
  "#1A1A1A": "#3A3833", "#1C1B19": "#3A3833",
};
const BORDER = {
  "#E8DDB0": "#3E3926", "#F1EAD0": "#3E3926",
  "#E5E3DE": "#3A3833", "#EDEBE6": "#3A3833", "#C8C4BA": "#4A4741", "#B5B0A5": "#4A4741", "#9C978C": "#55524B",
  "gray-300": "#4A4741", "white": "#1E1D1B", "#1C1B19": "#D6D2C9", "#1A1A1A": "#D6D2C9",
};
const KINDS = { text: ["color", TEXT], placeholder: ["color", TEXT], bg: ["background-color", BG],
  border: ["border-color", BORDER], divide: ["border-color", BORDER], ring: ["--tw-ring-color", BORDER] };

const PSEUDO = { hover: ":hover", focus: ":focus", "focus-visible": ":focus-visible", active: ":active", disabled: ":disabled", "focus-within": ":focus-within" };
const MEDIA = { sm: 640, md: 768, lg: 1024, xl: 1280 };

function files(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) files(p, out);
    else if (/\.(tsx|ts)$/.test(f)) out.push(p);
  }
  return out;
}

const TOKEN = /(?<![\w-])((?:[a-z-]+:)*)(text|bg|border|divide|ring|placeholder)-(\[#[0-9A-Fa-f]{3,8}\]|white|black|gray-\d{2,3})(\/\d{1,3})?(?![\w-])/g;
const esc = (s) => s.replace(/([^a-zA-Z0-9_-])/g, "\\$1");
const hexA = (hex, a) => {
  const n = parseInt(hex.slice(1), 16);
  return a == null ? hex : `rgb(${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255} / ${a})`;
};

const rules = new Map();
for (const f of files("src")) {
  for (const m of readFileSync(f, "utf8").matchAll(TOKEN)) {
    const [whole, variants, kind, rawColor, alpha] = m;
    const color = rawColor.startsWith("[") ? rawColor.slice(1, -1).toUpperCase() : rawColor;
    const [prop, map] = KINDS[kind];
    const dark = map[color];
    if (!dark) continue;
    const vs = variants ? variants.slice(0, -1).split(":") : [];
    if (vs.some((v) => !(v in PSEUDO) && !(v in MEDIA) && v !== "group-hover" && v !== "placeholder")) continue;
    let sel = "." + esc(whole);
    let prefix = ".dark ";
    for (const v of vs) if (PSEUDO[v]) sel += PSEUDO[v];
    if (vs.includes("group-hover")) prefix = ".dark .group:hover ";
    if (kind === "placeholder" || vs.includes("placeholder")) sel += "::placeholder";
    if (kind === "divide") sel += " > :not([hidden]) ~ :not([hidden])";
    const media = vs.find((v) => v in MEDIA);
    const value = hexA(dark, alpha ? Number(alpha.slice(1)) / 100 : null);
    const css = `${prefix}${sel}{${prop}:${value}}`;
    rules.set(css, media ? MEDIA[media] : 0);
  }
}

const plain = [...rules].filter(([, m]) => !m).map(([c]) => c).sort();
const byMedia = {};
for (const [c, m] of rules) if (m) (byMedia[m] ||= []).push(c);

let out = `/* Generated by scripts/gen-dark-theme.mjs — do not edit by hand. */\n`;
out += plain.join("\n") + "\n";
for (const m of Object.keys(byMedia).sort((a, b) => a - b)) out += `@media (min-width:${m}px){\n${byMedia[m].sort().join("\n")}\n}\n`;
mkdirSync("src/styles", { recursive: true });
writeFileSync("src/styles/dark-theme.css", out);
console.log(`wrote src/styles/dark-theme.css: ${rules.size} rules`);
